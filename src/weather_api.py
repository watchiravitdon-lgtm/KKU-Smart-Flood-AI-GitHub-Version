PROVINCES = dict(sorted(PROVINCES.items()))


def fetch_weather(province: str) -> dict:
    if province not in PROVINCES:
        raise ValueError("ไม่พบจังหวัดที่เลือก")

    lat, lon = PROVINCES[province]
    params = {
        "latitude": lat,
        "longitude": lon,
        "current": "temperature_2m,relative_humidity_2m,precipitation,wind_speed_10m",
        "hourly": "precipitation",
        "past_hours": 24,
        "forecast_hours": 1,
        "timezone": "Asia/Bangkok",
    }

    response = requests.get(OPEN_METEO_URL, params=params, timeout=15)
    response.raise_for_status()
    data = response.json()

    hourly_precip = data.get("hourly", {}).get("precipitation", [])
    rainfall_24h = round(sum(float(x or 0) for x in hourly_precip), 2)
    current = data.get("current", {})

    return {
        "province": province,
        "latitude": lat,
        "longitude": lon,
        "rainfall_24h": rainfall_24h,
        "temperature": float(current.get("temperature_2m", 0)),
        "humidity": float(current.get("relative_humidity_2m", 0)),
        "current_precipitation": float(current.get("precipitation", 0)),
        "wind_speed": float(current.get("wind_speed_10m", 0)),
        "updated_at": current.get("time", datetime.now().isoformat()),
    }
